/**
 * FIG-04 / audit 2026-11-15 A-10: a figure wears ITS face, not the default one, wherever the data allows.
 *
 * Two routes give a head its own face (head-face.ts): a printed LDraw head (its artwork, rasterised), or face art
 * seeded for its print id (route 2, `scripts/gen-face-art.py`, offline builds only). The audit found 152 of 235
 * favourite figures on the default face, and part of that was a lookup fault: BrickLink-lineage sources name a
 * printed head by its BrickLink item (`3626cpb2588.dat`, which no library ships), and the alias ladder dropped the
 * print and drew the plain `3626c`, although LDraw prints that very face as `3626cp0b` (its header says
 * `!KEYWORDS BrickLink 3626pb2588`). `HEAD_PRINT_LDRAW` (generated by `scripts/gen-head-print-ldraw.py`) is that
 * join, tried before the plain mould.
 */
import { existsSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { partAliasCandidates } from '../web/src/engine/ldraw-part-aliases.js';
import { namedHeadPrint } from '../scripts/face-census.ts';

describe('a BrickLink-named printed head resolves to the LDraw print of the same face', () => {
  it('tries the LDraw print before the plain mould', () => {
    // 10303's IOModel2V2 source: `3626cpb2588.dat` is LDraw's `3626cp0b` (official, keywords BrickLink 3626pb2588).
    expect(partAliasCandidates('3626cpb2588')[0]).toBe('3626cp0b');
    // The same print on the older mould names, and BrickLink's own spelling without a mould letter.
    expect(partAliasCandidates('3626bpb2588')[0]).toBe('3626cp0b');
    expect(partAliasCandidates('3626pb2588')[0]).toBe('3626cp0b');
    // The plain mould stays a later rung: a print LDraw lacks still falls back to a drawable head.
    expect(partAliasCandidates('3626cpb2588')).toContain('3626c');
  });

  it('leaves a print with no LDraw equivalent to the suffix ladder', () => {
    // 3626pb3484 (76417's goblin) has no LDraw print: the plain head, whose face art keys on the print id.
    expect(partAliasCandidates('3626cpb3484')[0]).toBe('3626c');
  });

  it('reads the print a head names from its part name or its HEAD_PRINT meta', () => {
    expect(namedHeadPrint('3626cpb2588.dat')).toBe('3626pb2588');
    expect(namedHeadPrint('3626c.dat', '3626pb3484')).toBe('3626pb3484');
    expect(namedHeadPrint('3626.dat')).toBeNull();
    expect(namedHeadPrint('92198pr0050.dat')).toBe('92198pr0050');
  });
});

void existsSync;
