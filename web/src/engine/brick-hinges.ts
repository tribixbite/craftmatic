// ─── Joint table ─────────────────────────────────────────────────────────────

/** A turning connector in a part's own frame (`hinge-joint-snaps.ts`). */
export interface JointSnap {
  /** `f` finger hinge, `c` clip, `y` cylinder (pin, bar, hole, axle, ring). */
  kind: 'f' | 'c' | 'y';
  /** `M` male, `F` female, `X` genderless (fingers and clips). */
  gender: string;
  /** A cylinder's section shapes: `R` round, `A` axle, `AR` both. */
  shapes: string;
  radius: number;
  /** Length along the axis, LDU (a cylinder runs from `p` along `a`; a centred clip straddles `p`). */
  length: number;
  p: Vec3;
  a: Vec3;
  slides: boolean;
  centred: boolean;
  /** A finger hinge's LDCad group: only the same group interlocks. */
  group: string;
}

const unpacked = new Map<string, JointSnap[]>();
function unpack(packed: string): JointSnap[] {
  return packed.split(';').map(s => {
    const t = s.split(' ');
    const n = (i: number): number => Number(t[i]);
    return {
      kind: t[0] as JointSnap['kind'], gender: t[1]!, shapes: t[2] === '-' ? '' : t[2]!, radius: n(3), length: n(4),
      p: [n(5), n(6), n(7)], a: [n(8), n(9), n(10)], slides: t[11]!.includes('S'), centred: t[11]!.includes('C'), group: t[12] === '-' ? '' : t[12]!,
    };
  });
}

/**
 * A part's turning connectors: its own row, else its base mould's (a printed
 * `3001pb12`, a BrickLink `bl_3830`, a lettered `4085c` fall back to `3001`,
 * `3830`, `4085`), the order the LDCad resolver uses.
 */
export function jointSnapsOf(part: string): readonly JointSnap[] {
  const stem = partStem(part);
  const cached = unpacked.get(stem);
  if (cached) return cached;
  const cands = [stem];
  const bare = stem.startsWith('bl_') ? stem.slice(3) : stem;
  if (bare !== stem) cands.push(bare);
  const m = /^(\d+)([a-z])?/.exec(bare);
  if (m) { if (m[2]) cands.push(m[1]! + m[2]); cands.push(m[1]!); }
  let out: JointSnap[] = [];
  for (const c of cands) { const row = HINGE_JOINT_SNAPS[c]; if (row) { out = unpack(row); break; } }
  unpacked.set(stem, out);
  return out;
}

// ─── Small vector helpers ────────────────────────────────────────────────────

const IDENTITY: readonly number[] = [1, 0, 0, 0, 1, 0, 0, 0, 1];
const apply = (m: readonly number[], v: Vec3): Vec3 => [m[0]! * v[0] + m[1]! * v[1] + m[2]! * v[2], m[3]! * v[0] + m[4]! * v[1] + m[5]! * v[2], m[6]! * v[0] + m[7]! * v[1] + m[8]! * v[2]];
const add = (a: Vec3, b: Vec3): Vec3 => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
const sub = (a: Vec3, b: Vec3): Vec3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const scale = (a: Vec3, k: number): Vec3 => [a[0] * k, a[1] * k, a[2] * k];
const dot = (a: Vec3, b: Vec3): number => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross = (a: Vec3, b: Vec3): Vec3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const len = (a: Vec3): number => Math.hypot(a[0], a[1], a[2]);
const norm = (a: Vec3): Vec3 => { const l = len(a) || 1; return [a[0] / l, a[1] / l, a[2] / l]; };
const toWorld = (b: ParsedBrick, v: Vec3): Vec3 => add([b.x, b.y, b.z], apply(b.rot ?? IDENTITY, v));

export interface Box { min: Vec3; max: Vec3 }
const overlapOn = (a: Box, b: Box, i: number): number => Math.min(a.max[i]!, b.max[i]!) - Math.max(a.min[i]!, b.min[i]!);
const inBox = (p: Vec3, b: Box, pad: number): boolean =>
  p[0] > b.min[0] + pad && p[0] < b.max[0] - pad && p[1] > b.min[1] + pad && p[1] < b.max[1] - pad && p[2] > b.min[2] + pad && p[2] < b.max[2] - pad;
const volume = (b: Box): number => Math.max(0, b.max[0] - b.min[0]) * Math.max(0, b.max[1] - b.min[1]) * Math.max(0, b.max[2] - b.min[2]);

/** Right-handed rotation of `p` by `deg` about the line through `pivot` along unit `axis` (Rodrigues). */
function rotateAbout(p: Vec3, pivot: Vec3, axis: Vec3, deg: number): Vec3 {
  const r = deg * Math.PI / 180, c = Math.cos(r), s = Math.sin(r);
  const v = sub(p, pivot);
  return add(pivot, add(add(scale(v, c), scale(cross(axis, v), s)), scale(axis, dot(axis, v) * (1 - c))));
}

// ─── Joints ──────────────────────────────────────────────────────────────────

/** Tolerances, LDU: how far off one line two connectors may sit and still be one joint. */
const LINE_TOLERANCE = 1.6;
/** Two cylinders mate when their radii differ by at most this (a 4 LDU bar in a 4 LDU clip, a pin in a hole). */
const RADIUS_TOLERANCE = 1.1;
/** Axes this close to parallel (|cos|) share a line. */
const PARALLEL = 0.985;

interface WorldSnap { brick: ParsedBrick; snap: JointSnap; p: Vec3; a: Vec3; from: number; to: number }

/** A connection between two placements through their connectors, about one line. */
export interface HingeJoint {
  a: ParsedBrick;
  b: ParsedBrick;
  /** A point on the joint's line and its unit direction, LDraw. */
  point: Vec3;
  axis: Vec3;
  /** Finger hinge, clip on a bar, or cylinder in cylinder. */
  type: 'finger' | 'clip' | 'cylinder';
  /** It can turn (an axle in an axle hole cannot). */
  turns: boolean;
  /** The radius the joint turns on, LDU: 4 a bar, 6 a Technic pin or axle, 7 and up a turntable ring (0 for fingers and clips). */
  radius: number;
}

/** The span a connector covers along its own axis, measured from its position: a centred one straddles it. */
function spanOf(s: JointSnap): [number, number] {
  const l = Math.max(s.length, 1);
  // LDCad lays a snap's sections from its position toward its local -Y (63965's bar
  // runs from its stop at y 18 up to its tip at y -102.5), i.e. against `a`.
  return s.centred ? [-l / 2, l / 2] : [-l, 0];
}

/** Distance from `p` to the line through `q` along unit `a`. */
const lineDistance = (p: Vec3, q: Vec3, a: Vec3): number => { const v = sub(p, q); return len(sub(v, scale(a, dot(v, a)))); };

/**
 * Every joint between two placements (`bricks`): compatible connectors on one
 * line whose spans overlap. Uses a spatial hash over connector positions.
 */
export function findHingeJoints(bricks: readonly ParsedBrick[]): HingeJoint[] {
  const snaps: WorldSnap[] = [];
  for (const b of bricks) {
    for (const s of jointSnapsOf(b.part)) {
      const R = b.rot ?? IDENTITY;
      const a = norm(apply(R, s.a));
      const [f, t] = spanOf(s);
      snaps.push({ brick: b, snap: s, p: toWorld(b, s.p), a, from: f, to: t });
    }
  }
  const CELL = 24;
  const cells = new Map<string, WorldSnap[]>();
  const key = (x: number, y: number, z: number): string => `${x},${y},${z}`;
  for (const w of snaps) {
    // Register along the connector's whole span so a long bar meets a clip anywhere on it.
    const steps = Math.max(1, Math.ceil((w.to - w.from) / CELL));
    const seen = new Set<string>();
    for (let i = 0; i <= steps; i++) {
      const q = add(w.p, scale(w.a, w.from + (w.to - w.from) * i / steps));
      const k = key(Math.floor(q[0] / CELL), Math.floor(q[1] / CELL), Math.floor(q[2] / CELL));
      if (seen.has(k)) continue;
      seen.add(k);
      const l = cells.get(k) ?? []; l.push(w); cells.set(k, l);
    }
  }
  const joints: HingeJoint[] = [];
  const done = new Set<string>();
  const ids = new Map<ParsedBrick, number>();
  bricks.forEach((b, i) => ids.set(b, i));
  for (const list of cells.values()) {
    for (let i = 0; i < list.length; i++) for (let j = i + 1; j < list.length; j++) {
      const u = list[i]!, v = list[j]!;
      if (u.brick === v.brick) continue;
      const c = Math.abs(dot(u.a, v.a));
      if (c < PARALLEL) continue;
      const mated = mate(u, v);
      if (!mated) continue;
      const ia = ids.get(u.brick)!, ib = ids.get(v.brick)!;
      const k = ia < ib ? `${ia}|${ib}|${mated.type}` : `${ib}|${ia}|${mated.type}`;
      if (done.has(k)) continue;
      done.add(k);
      joints.push({ a: u.brick, b: v.brick, point: mated.point, axis: u.a, type: mated.type, turns: mated.turns, radius: mated.radius });
    }
  }
  return joints;
}

/** Whether two connectors on (near) one line mate, and how. */
function mate(u: WorldSnap, v: WorldSnap): { type: HingeJoint['type']; turns: boolean; point: Vec3; radius: number } | null {
  const ku = u.snap.kind, kv = v.snap.kind;
  // Spans along u's axis: u's own, and v's projected onto it.
  const along = (w: WorldSnap, t: number): number => dot(sub(add(w.p, scale(w.a, t)), u.p), u.a);
  const overlap = (w: WorldSnap, slack: number): boolean => {
    const a0 = Math.min(along(w, w.from), along(w, w.to)), a1 = Math.max(along(w, w.from), along(w, w.to));
    return Math.min(a1, u.to) - Math.max(a0, u.from) > -slack;
  };
  if (ku === 'f' && kv === 'f') {
    if (u.snap.group && v.snap.group && u.snap.group !== v.snap.group) return null;
    if (lineDistance(v.p, u.p, u.a) > LINE_TOLERANCE || !overlap(v, 1)) return null;
    return { type: 'finger', turns: true, point: u.p, radius: 0 };
  }
  if ((ku === 'c' && kv === 'y') || (ku === 'y' && kv === 'c')) {
    const clip = ku === 'c' ? u : v, bar = ku === 'c' ? v : u;
    // A clip grips a 4 LDU bar (the bar's male cylinder, or a bar tube's).
    if (bar.snap.gender !== 'M' || Math.abs(bar.snap.radius - 4) > RADIUS_TOLERANCE) return null;
    if (lineDistance(clip.p, bar.p, bar.a) > LINE_TOLERANCE + 0.5) return null;
    const t = dot(sub(clip.p, bar.p), bar.a);
    if (t < bar.from - 4 || t > bar.to + 4) return null;
    return { type: 'clip', turns: true, point: clip.p, radius: 0 };
  }
  if (ku === 'y' && kv === 'y') {
    const genders = u.snap.gender + v.snap.gender;
    if (genders !== 'MF' && genders !== 'FM') return null;
    if (Math.abs(u.snap.radius - v.snap.radius) > RADIUS_TOLERANCE) return null;
    if (lineDistance(v.p, u.p, u.a) > LINE_TOLERANCE || !overlap(v, -1)) return null;
    const male = u.snap.gender === 'M' ? u : v, female = male === u ? v : u;
    // An axle in an axle hole is locked; a round pin, or an axle in a round hole, turns.
    const turns = !(male.snap.shapes.includes('A') && female.snap.shapes.includes('A'));
    return { type: 'cylinder', turns, point: female.p, radius: Math.min(male.snap.radius, female.snap.radius) };
  }
  return null;
}

// ─── Rigid connectivity ──────────────────────────────────────────────────────

/** A part this small (every side at most this, LDU) embedded in another is held by it: a pin, a bar, a clip, a 1 x 1. */
const SMALL_PART_LDU = 24;
/** How deep (LDU, every axis) a small part must sit inside another to count as held. */
const EMBED_LDU = 2;

export interface RigidGraph {
  /** Neighbours by rigid connection, per placement index. */
  edges: Array<Set<number>>;
  /** The first rule that linked each pair (`"i|j"`, i < j): `stud`, `stud group`, `embedded`, `joint <type>` - the diagnostics' answer to "what holds this door shut". */
  why: Map<string, string>;
}

/**
 * The model's rigid connections, over placement indices of `bricks`
 * (see the module comment, rule 2). `boxes[i]` is placement i's world box.
 */
export function rigidConnections(bricks: readonly ParsedBrick[], boxes: readonly Box[], meshes: ReadonlyArray<LdrawPartMesh | null>, descriptions: readonly string[], joints: readonly HingeJoint[]): RigidGraph {
  const n = bricks.length;
  const edges: Array<Set<number>> = Array.from({ length: n }, () => new Set<number>());
  const why = new Map<string, string>();
  const link = (i: number, j: number, reason: string): void => { if (i === j) return; edges[i]!.add(j); edges[j]!.add(i); const k = i < j ? `${i}|${j}` : `${j}|${i}`; if (!why.has(k)) why.set(k, reason); };
  const CELL = 40;
  const grid = new Map<string, number[]>();
  boxes.forEach((b, i) => {
    for (let x = Math.floor(b.min[0] / CELL); x <= Math.floor(b.max[0] / CELL); x++)
      for (let y = Math.floor(b.min[1] / CELL); y <= Math.floor(b.max[1] / CELL); y++)
        for (let z = Math.floor(b.min[2] / CELL); z <= Math.floor(b.max[2] / CELL); z++) {
          const k = `${x},${y},${z}`; const l = grid.get(k) ?? []; l.push(i); grid.set(k, l);
        }
  });
  const near = (p: Vec3): number[] => grid.get(`${Math.floor(p[0] / CELL)},${Math.floor(p[1] / CELL)},${Math.floor(p[2] / CELL)}`) ?? [];
  const neighbours = (b: Box): Set<number> => {
    const out = new Set<number>();
    for (let x = Math.floor((b.min[0] - 1) / CELL); x <= Math.floor((b.max[0] + 1) / CELL); x++)
      for (let y = Math.floor((b.min[1] - 1) / CELL); y <= Math.floor((b.max[1] + 1) / CELL); y++)
        for (let z = Math.floor((b.min[2] - 1) / CELL); z <= Math.floor((b.max[2] + 1) / CELL); z++)
          for (const j of grid.get(`${x},${y},${z}`) ?? []) out.add(j);
    return out;
  };
  const isTile = (d: string): boolean => /^(Tile|Roof Tile)\b|\b(No Studs|without Studs|Smooth)\b/i.test(d.replace(/^[~=_]+\s*/, ''));
  /**
   * Whether two parts sit square to each other (their relative rotation is a
   * signed permutation). A stud only holds a part pressed onto it square: a
   * leaf the source left swung 19 degrees open stands on the floor's studs
   * but is not on them (10354's round door), and a turntable's load is not
   * square to its base. The one-stud round parts that do turn on a stud are
   * not hinges this detector moves.
   */
  const aligned = (i: number, j: number): boolean => {
    const A = bricks[i]!.rot ?? IDENTITY, B = bricks[j]!.rot ?? IDENTITY;
    for (let r = 0; r < 3; r++) for (let c = 0; c < 3; c++) {
      // (A^T B)[r][c]
      const v = A[r]! * B[c]! + A[3 + r]! * B[3 + c]! + A[6 + r]! * B[6 + c]!;
      const a = Math.abs(v);
      if (a > 0.03 && Math.abs(a - 1) > 0.03) return false;
    }
    return true;
  };
  for (let i = 0; i < n; i++) {
    const m = meshes[i], b = bricks[i]!, box = boxes[i]!;
    // 2a. A stud standing inside another part's box, the two square to each other.
    if (m && m.studs.length) {
      for (const s of m.studs) {
        const c = toWorld(b, s.center), u = norm(apply(b.rot ?? IDENTITY, s.up));
        const q = add(c, scale(u, 2));
        for (const j of near(q)) if (j !== i && inBox(q, boxes[j]!, 0.3) && aligned(i, j)) link(i, j, 'stud');
      }
    }
    for (const j of neighbours(box)) {
      if (j <= i) continue;
      const o = boxes[j]!;
      const ox = overlapOn(box, o, 0), oy = overlapOn(box, o, 1), oz = overlapOn(box, o, 2);
      // 2b. Stacked square: one part's top face meets the other's bottom face over
      // a stud's footprint, and the lower part has studs there. The mesh lists
      // the studs a part draws with `stud*.dat`; one whose studs are a `stug`
      // stud-group primitive (3010, 3958) lists none, so for it the description
      // decides (a tile or a stud-less brick holds nothing on top).
      const stacked = (lo: number, hi: number): boolean => {
        const lm = meshes[lo];
        if (!lm || Math.abs(boxes[lo]!.min[1] - boxes[hi]!.max[1]) > 1.2 || ox < 6 || oz < 6 || !aligned(lo, hi)) return false;
        const up = lm.studs.filter(s => apply(bricks[lo]!.rot ?? IDENTITY, s.up)[1] < -0.9);
        if (!up.length) return lm.studs.length === 0 && !isTile(descriptions[lo]!);
        const h = boxes[hi]!;
        return up.some(s => { const c = toWorld(bricks[lo]!, s.center); return c[0] > h.min[0] + 1 && c[0] < h.max[0] - 1 && c[2] > h.min[2] + 1 && c[2] < h.max[2] - 1; });
      };
      if (stacked(i, j) || stacked(j, i)) { link(i, j, 'stacked'); continue; }
      // 2c. A small part embedded in another (a pin in a beam, a bar in a hole, a clip on a plate).
      if (ox > EMBED_LDU && oy > EMBED_LDU && oz > EMBED_LDU) {
        const small = (k: number): boolean => { const bb = boxes[k]!; return bb.max[0] - bb.min[0] <= SMALL_PART_LDU + 0.5 && bb.max[1] - bb.min[1] <= SMALL_PART_LDU + 0.5 && bb.max[2] - bb.min[2] <= SMALL_PART_LDU + 0.5; };
        // Square to each other only: the box of a part turned off the grid (a leaf left
        // open) swells over its neighbours, which it does not touch.
        if ((small(i) || small(j)) && aligned(i, j)) link(i, j, 'embedded');
      }
    }
  }
  // 2d. Joints: every one that does not turn holds rigidly; the turning ones are the stage's to cut.
  const index = new Map<ParsedBrick, number>();
  bricks.forEach((b, i) => index.set(b, i));
  for (const jn of joints) {
    const i = index.get(jn.a), j = index.get(jn.b);
    if (i !== undefined && j !== undefined) link(i, j, `joint ${jn.type}`);
  }
  return { edges, why };
}

