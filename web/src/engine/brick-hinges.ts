/**
 * BRICK-BUILT doors, gates, flaps and mechanisms: an assembly of ordinary
 * bricks that moves because it hangs on a joint that turns.
 *
 * A moulded door is found by its description (`interactiveKindOf`); a door
 * built from plates and tiles on two clips, or a castle gate on hinge bricks,
 * has no description to read. What it has is a JOINT: a finger hinge (3937 +
 * 6134, click hinges 44301/60471), a swivel hinge brick or plate (3830/3831,
 * 2429/2430), a clip on a bar, a turntable ring, a Technic pin or axle in a
 * round hole. The rule (docs/bedrock-interactivity.md, "Brick-built doors,
 * gates and mechanisms"):
 *
 *   1. Every placement's TURNING connectors come from LDCad's shadow library
 *      (`hinge-joint-snaps.ts`, generated by scripts/gen-hinge-joint-snaps.py).
 *      Two placements whose connectors are compatible (finger to finger of the
 *      same group, a clip on a bar, a male cylinder in a female one of the
 *      same radius) and lie on one line are a JOINT about that line. An axle in
 *      an axle hole is a joint that does not turn: a rigid connection.
 *   2. The model's RIGID connections: a stud of one part standing inside the
 *      other's box (a stacked brick, a SNOT plate on a bracket), a stud-group
 *      part's top face under another part's bottom face, a small part embedded
 *      in another (a pin, a bar, a clip), and every joint that does not turn.
 *   3. All the turning joints on one line are cut together (a door hangs on
 *      two hinges on one line). If that splits off an assembly - one no other
 *      connection holds to the rest of the model - the assembly MOVES about the
 *      line, and its side of each joint moves with it.
 *   4. The assembly is classed by its shape against the line, and every class
 *      was tightened by a visual review of what it found over the 40
 *      favourites (docs/bedrock-interactivity.md, "Brick-built doors, gates
 *      and mechanisms"): a PANEL (its parts cover half its outline) beside a
 *      vertical line, standing on a floor, is a door (a lintel over it) or a
 *      gate (none); one under a lintel but not on a floor, or too tall for a
 *      doorway, is a door leaf or hinged panel that swings with its collider
 *      kept. A flat panel (a lid) or a standing one on a level line (a flap)
 *      moves only on a hinge proper. A thick section on hinge bricks or plates
 *      is a WING when it swings out into free air and could not swing in. A
 *      mechanism turns a step per tap only on a turntable. A bar in a tube or
 *      a hollow stud swings nothing (railings, ladders, lamp posts), and
 *      mostly-Technic assemblies are a mechanism's insides.
 *
 * Nothing here names a set. A rule that finds nothing reports why for every
 * joint line it cut (`BrickHingeDiagnostics`), so the next rule is written
 * from evidence.
 */

