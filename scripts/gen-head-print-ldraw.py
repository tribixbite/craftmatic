#!/usr/bin/env python3
"""
Generate web/src/engine/head-print-ldraw.ts: which PRINTED LDraw head a
BrickLink head-print id is.

Sources in the BrickLink lineage (Studio's `.io` exports and clego's
IOModel2V2 conversions) name a printed head by its BrickLink item number as if
it were an LDraw file: `3626cpb2588.dat`. No library ships that name, so the
alias ladder stripped the print suffix and drew the PLAIN `3626c` - a blank
face (audit 2026-11-15 A-10: every head of 10303 named its print, none drew
it). LDraw does carry many of those prints under its own numbering, and says
which BrickLink item each one is in its header: `3626cp0b.dat` has
`0 !KEYWORDS BrickLink 3626pb2588`. This table is that join, so the ladder
(`partAliasCandidates`, ldraw-part-aliases.ts) can try the real print before
the plain mould.

The join and its acceptance rule are `gen-ldd-print-map.py`'s (imported, not
copied): a candidate must be served by a library the renderer reads (Studio's
install, the upstream official + unofficial trees in clego's `ldraw_ref/`) and
framed like its base mould (bounding box within 0.6 LDU of `3626c` / `92198` /
`92240`), so drawing it at the plain head's transform cannot move the head.
Official LDraw is preferred, then upstream unofficial, then a Studio copy.

Keys are BrickLink's shared head key (`3626pb<N>`: BL numbers a head print
once across the 3626b/3626c/28621 moulds); mini-doll prints are keyed by
their Rebrickable id (`92198pr<N>`, `28649pr<N>`), the id the converters write.

Usage: python -I scripts/gen-head-print-ldraw.py
"""
import importlib.util
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / 'web' / 'src' / 'engine' / 'head-print-ldraw.ts'

spec = importlib.util.spec_from_file_location('gen_ldd_print_map', REPO / 'scripts' / 'gen-ldd-print-map.py')
assert spec and spec.loader
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)

MINIFIG_KEY = re.compile(r'^3626pb\d+[a-z]?$')
DOLL_KEY = re.compile(r'^(92198|28649)pr\d+[a-z]?$')


def main() -> int:
    g.build_index()
    stems, by_bl, by_rb = g.printed_head_files()
    framed = {s for s in stems if g.same_frame(s)}

    def pick(cands):
        ok = sorted((c for c in cands if c in framed), key=g.preference)
        return ok[0] if ok else None

    rows: dict[str, str] = {}
    for key, cands in by_bl.items():
        if MINIFIG_KEY.match(key):
            hit = pick(cands)
            if hit:
                rows[key] = hit
    for key, cands in by_rb.items():
        if DOLL_KEY.match(key):
            hit = pick(cands)
            if hit:
                rows[key] = hit
    lines = [
        '/**',
        ' * GENERATED by `python -I scripts/gen-head-print-ldraw.py` - do not edit by hand.',
        ' *',
        ' * BrickLink head-print id (`3626pb<N>`) or mini-doll Rebrickable print id',
        ' * (`92198pr<N>`) -> the printed LDraw head that IS that print, from the',
        " * libraries' own `!KEYWORDS BrickLink/Rebrickable` headers and Studio's",
        ' * BL column, kept only when framed like its base mould. Read by the alias',
        ' * ladder (`partAliasCandidates`) and the face census.',
        ' */',
        'export const HEAD_PRINT_LDRAW: Readonly<Record<string, string>> = Object.freeze({',
    ]
    lines += [f"  '{k}': '{v}'," for k, v in sorted(rows.items())]
    lines += ['});', '']
    OUT.write_bytes('\n'.join(lines).encode('utf-8'))
    n_fig = sum(1 for k in rows if k.startswith('3626'))
    print(f'printed heads served {len(stems)}, framed {len(framed)}; rows {len(rows)} '
          f'({n_fig} minifig, {len(rows) - n_fig} mini-doll) -> {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
