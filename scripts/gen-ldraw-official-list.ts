/**
 * Writes `web/src/engine/ldraw-official-parts.generated.ts`: the sorted names (no `.dat`) of every file in the
 * official LDraw library's `parts/` folder, read from `ldraw_ref/_archives/complete.zip`. Official mode
 * (`part-source.ts`) uses it to tell an official part from a Studio edit that shares its path.
 *
 * Usage: `bun scripts/gen-ldraw-official-list.ts [path/to/complete.zip]`
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { unzipSync } from 'fflate';

const ZIP = process.argv[2] ?? 'C:/git/clego/ldraw_ref/_archives/complete.zip';
const OUT = resolve(import.meta.dirname, '../web/src/engine/ldraw-official-parts.generated.ts');

const names = new Set<string>();
// `filter` sees every entry's name without inflating it: only the central directory is read.
unzipSync(new Uint8Array(readFileSync(ZIP)), {
  filter: file => {
    const m = /^ldraw\/parts\/([^/]+)\.dat$/i.exec(file.name);
    if (m) names.add(m[1]!.toLowerCase());
    return false;
  },
});
if (names.size < 10000) throw new Error(`only ${names.size} official parts found in ${ZIP}; refusing to write a short list`);

const sorted = [...names].sort();
const body = sorted.map(n => `  '${n}',`).join('\n');
writeFileSync(OUT, `/**
 * GENERATED by scripts/gen-ldraw-official-list.ts from ldraw_ref/_archives/complete.zip - do not edit.
 * ${sorted.length} names of the official LDraw library's parts/ folder (lower case, no .dat), sorted.
 */
export const OFFICIAL_PART_NAMES: readonly string[] = [
${body}
];
`, 'utf-8');
console.log(`wrote ${sorted.length} names to ${OUT}`);
