import { readFileSync } from 'node:fs';
import { buildMassing } from '../web/src/brickgen/massing/index.js';
import { siteFromOverpass } from '../web/src/brickgen/site/osm.js';
import { plainMassingLattice } from '../web/src/brickgen/bricker/plain-massing.js';
import { brickLattice } from '../web/src/brickgen/bricker/index.js';
const which = process.argv[2] ?? 'notre-dame';
const target = Number(process.argv[3] ?? 1);
const nd = JSON.parse(readFileSync(`test/fixtures/osm/${which}.overpass.json`, 'utf8'));
const r = siteFromOverpass(nd, { retrieved: '2026-11-09', url: 'x', ...(which==='notre-dame'?{buildingId:'way/201611261'}:{}) });
const m = buildMassing(r.site, { roles: r.roles, scale: { target } });
console.log(JSON.stringify(m.massing.scale));
let t = Date.now();
const p = plainMassingLattice(m.massing);
console.log('lattice', p.lattice.dims, Date.now()-t, 'ms', p.notes);
t = Date.now();
const b = brickLattice(p.lattice, { scale: m.massing.scale });
console.log('brick', Date.now()-t, 'ms', b.plan.elements.length, JSON.stringify(b.report), b.repairs, b.openings);
