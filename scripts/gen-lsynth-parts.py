#!/usr/bin/env python3
"""
Generate web/src/engine/lsynth-parts.ts: the LSynth part files (`LS00.dat` .. `LS102.dat`) as text.

Why: LSynth (the LDraw hose/band synthesiser) writes a synthesised hose as hundreds of placements of its own
segment parts - `LS51` (Flex-System hose cross section), `LS60` (string segment), `LS21` (pneumatic hose), `LS11`
(cable) ... - and ships those parts with the TOOL, not with the LDraw library. No library this project reads has
them (Studio carries only `ls10.dat`), so every such placement resolved to nothing: the export drew each as its
bounding box (8097 Slave I: 40 `ls11` boxes, generality census 2026-11-16) and the viewer drew a 4.5 LDU stand-in
cylinder for all of them. Corpus census 2026-11-16: 160,615 placements of 19 LSynth names in 266 source files.

Source: Holly-Wood.it's LSynth 3.1 constraint/segment package, https://www.holly-wood.it/files/lsynth/Constraints_3-1.zip
(fetched 2026-11-16; files dated 2009-11-11 .. 2011-06-12), the parts LSynth's own installer copies into
`ldraw/parts`. Licence: each file's own header, "Redistributable under CCAL version 2.0" - kept verbatim with the
author lines. Only the `LS*.dat` files are taken: the package's `572a.dat` and `757.dat` are LDraw parts the
libraries already ship in a newer revision.

Usage: python -I scripts/gen-lsynth-parts.py <directory holding the unzipped LS*.dat files>
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / 'web' / 'src' / 'engine' / 'lsynth-parts.ts'


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    files = sorted(p for p in src.iterdir() if p.suffix.lower() == '.dat' and p.name.lower().startswith('ls'))
    if not files:
        sys.exit(f'no LS*.dat files in {src}')
    rows = []
    for p in files:
        raw = p.read_bytes()
        # Most files are ASCII; LS22's author line is Latin-1 ("Gl\xfcckner").
        try:
            text = raw.decode('utf-8')
        except UnicodeDecodeError:
            text = raw.decode('latin-1')
        text = text.replace('\r\n', '\n').replace('\r', '\n').rstrip('\n') + '\n'
        rows.append((p.stem.lower(), text))
    out = [
        '// AUTO-GENERATED by scripts/gen-lsynth-parts.py - do not edit by hand.',
        '// The LSynth 3.1 part files (Holly-Wood.it Constraints_3-1.zip), each under its own header:',
        '// "Redistributable under CCAL version 2.0". Read by `synthesizedPartText` (ldraw-part-aliases.ts) only after',
        '// a definitive library miss, so a library or embedded definition of the same name always wins.',
        '',
        '/** LSynth part text by lower-case stem (`ls51`), as the tool ships it. */',
        'export const LSYNTH_PARTS: Readonly<Record<string, string>> = Object.freeze({',
    ]
    for stem, text in rows:
        out.append(f'  {json.dumps(stem)}: {json.dumps(text, ensure_ascii=False)},')
    out += ['});', '']
    OUT.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(f'wrote {OUT} with {len(rows)} parts')


if __name__ == '__main__':
    main()
