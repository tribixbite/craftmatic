/**
 * Stable Script API audit (BIZ-24, M15): no beta API may reach a Marketplace pack.
 *
 * Every script a pack emits is type-checked (`checkJs`, the programmatic form of `// @ts-check`) against the
 * VENDORED STABLE `@minecraft/server` / `server-ui` typings (`scripts/script-api-typings/`) of the version the
 * pack's manifest declares. The stable typings simply lack a beta API, so a typed use of one is a diagnostic.
 *
 * Two things the checker alone cannot see, both handled here:
 *  - the packs hand `world` / `system` to their runtimes as PARAMETERS (`(function runtime(world, system){..}).toString()`),
 *    so inside a runtime they are implicit `any`. A second pass matches member and import NAMES against
 *    `script-api-typings/stability.json` (names only in the beta typings, or only after the declared stable version;
 *    generated by `_script_api_stability_gen.ts`). Only COMPOUND names (an interior capital: `chatSend`) are matched by
 *    name, because a single word (`direction`, `blocks`, `at`) is ordinary script vocabulary. A name the file declares
 *    itself (a property key, function, variable, parameter) is skipped.
 *    TODO(m15-single-word): single-word beta names are checked only where the receiver is typed.
 *    TODO(m15-component-ids): string ids (`getComponent('minecraft:...')`, entity-event names) are not audited off-type.
 *  - manifests: a `-beta` / `-rc` / `-preview` dependency version, a module other than `@minecraft/server` /
 *    `@minecraft/server-ui` (gametest, net, admin, editor are all beta), or an import the manifest does not declare.
 *
 * Usage: bun scripts/_script_api_audit.ts <pack.mcaddon|pack.mcpack|folder>... [--json=<report.json>]
 *   Exits 1 on any finding. The report lists every stable/beta API the scripts use (`apis`), for the release bundle.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unzipSync } from 'fflate';
import * as ts from 'typescript';
import { STABLE_TYPINGS, type StabilityTable } from './_script_api_stability_gen.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const TYPINGS_ROOT = join(HERE, 'script-api-typings');

/** The only `@minecraft/*` script modules that are stable; every other module is beta. */
export const STABLE_MODULES = ['@minecraft/server', '@minecraft/server-ui'] as const;

/** One script source: a pack-relative path and its text. */
export interface ScriptSource { path: string; text: string }

/** What kind of problem a finding is. */
export type FindingKind =
  | 'beta-api'             // a name that exists only in the beta typings
  | 'newer-than-declared'  // stable, but after the version the manifest declares
  | 'unknown-api'          // the stable typings lack it and the beta ones do not name it (typo, or removed API)
  | 'module'               // import of a non-stable module
  | 'manifest'             // beta dependency version, non-stable module, undeclared import
  | 'typings';             // no vendored typings for the declared version

/** One audit finding, located in the script (or manifest) it came from. */
export interface Finding { kind: FindingKind; file: string; line: number; column: number; message: string }

/** An API the scripts use, with its stability. */
export interface ApiUse {
  /** Module the API belongs to, e.g. `@minecraft/server`. */
  module: string;
  /** `Owner.member` (`World.getAllPlayers`) or the exported name (`world`). */
  name: string;
  stability: 'stable' | 'beta' | 'newer-than-declared';
  count: number;
  /** First use, `file:line`. */
  first: string;
}

/** The audit result. `ok` is true when there are no findings. */
export interface AuditResult {
  ok: boolean;
  findings: Finding[];
  /** Not failing: a member the stable typings lack that no beta typing names either (typo, narrow typings). */
  warnings: Finding[];
  apis: ApiUse[];
  scriptsChecked: number;
  /** Type diagnostics that are not API-existence problems (argument types and the like); reported, not failing. */
  typeWarnings: number;
}

/** `server` -> `2.9.0` per module, as declared by a manifest. */
export type DeclaredVersions = Record<string, string>;

/** Versions the generated packs declare today (`engine/mcpack.ts`). */
export const DEFAULT_DECLARED: DeclaredVersions = { ...STABLE_TYPINGS.declared };

const stability = JSON.parse(readFileSync(join(TYPINGS_ROOT, 'stability.json'), 'utf8')) as StabilityTable;
const BETA_ONLY = new Set(stability.betaOnly);
/** name -> `<module>@<version>`; a Map because a plain object answers `toString` / `constructor` from its prototype. */
const ADDED_AFTER = new Map(Object.entries(stability.addedAfterDeclared));

/** Numeric `[major, minor, patch]` of a version string; undefined for a pre-release (`-beta`, `-rc`, ...). */
function stableVersion(v: string): [number, number, number] | undefined {
  const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(v.trim());
  return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : undefined;
}

/** True when stable version `a` is older than `b`. */
function olderThan(a: string, b: string): boolean {
  const x = stableVersion(a); const y = stableVersion(b);
  if (!x || !y) return false;
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i]! < y[i]!;
  return false;
}

/** A name worth matching without type information: it has an interior capital (`chatSend`, `getWeather`, `BlockVibrationPropertiesComponent`). */
const isCompound = (name: string): boolean => /[a-z0-9][A-Z]/.test(name);

/** Vendored typings file for a module at a version, or undefined when none is vendored. */
function typingsFile(mod: string, version: string): string | undefined {
  const p = join(TYPINGS_ROOT, `${mod}@${version}`, 'index.d.ts');
  return existsSync(p) ? p : undefined;
}

/** The newest vendored version of a module (fallback when a manifest declares one that is not vendored). */
function newestVendored(mod: string): string {
  const versions = readdirSync(TYPINGS_ROOT).filter(d => d.startsWith(`${mod}@`)).map(d => d.slice(mod.length + 1)).filter(v => stableVersion(v));
  versions.sort((a, b) => (olderThan(a, b) ? 1 : -1));
  return versions[0] ?? '';
}

const AMBIENT = 'declare const console: { log(...a: unknown[]): void; warn(...a: unknown[]): void; error(...a: unknown[]): void; info(...a: unknown[]): void };\n';
const VIRTUAL = '/audit/';

/** TS diagnostic codes meaning "this API member / export does not exist". */
const MISSING_MEMBER = new Set([2305, 2339, 2551, 2724, 2694, 2304, 2552, 2614]);
const MISSING_MODULE = 2307;

/** Owner type name of a declaration inside the vendored typings (`World` for `World.getAllPlayers`). */
function ownerOf(decl: ts.Declaration): string {
  const p = decl.parent as ts.Node | undefined;
  if (p && (ts.isClassDeclaration(p) || ts.isInterfaceDeclaration(p) || ts.isEnumDeclaration(p)) && p.name) return p.name.text;
  return '';
}

/** Which vendored module a declaration came from (by its typings folder). */
function moduleOfFile(fileName: string): string {
  const m = /script-api-typings[\\/](server-ui|server|common)@/.exec(fileName);
  return m ? `@minecraft/${m[1]}` : '';
}

/**
 * Audit script sources against the stable typings of `declared` versions.
 * Paths are reported as given. Pass the module versions the pack's manifest declares.
 */
export function auditScripts(files: readonly ScriptSource[], declared: DeclaredVersions = DEFAULT_DECLARED): AuditResult {
  const findings: Finding[] = [];
  const jsFiles = files.filter(f => /\.(m?js)$/.test(f.path));
  const where = (sf: ts.SourceFile, pos: number, display: string): { file: string; line: number; column: number } => {
    const { line, character } = sf.getLineAndCharacterOfPosition(pos);
    return { file: display, line: line + 1, column: character + 1 };
  };

  // Resolve typings per module at the declared version (falling back to the newest vendored one, with a finding).
  const paths: Record<string, string[]> = {};
  for (const mod of ['server', 'server-ui'] as const) {
    let v = declared[mod] ?? DEFAULT_DECLARED[mod]!;
    let file = typingsFile(mod, v);
    if (!file) {
      const fallback = newestVendored(mod);
      findings.push({ kind: 'typings', file: '(manifest)', line: 0, column: 0, message: `no vendored typings for @minecraft/${mod} ${v}; checked against ${fallback}. Vendor them under scripts/script-api-typings/.` });
      v = fallback;
      file = typingsFile(mod, v)!;
    }
    paths[`@minecraft/${mod}`] = [file.replace(/\\/g, '/')];
  }
  paths['@minecraft/common'] = [join(TYPINGS_ROOT, `common@${STABLE_TYPINGS.declared.common}`, 'index.d.ts').replace(/\\/g, '/')];

  const virtual = new Map<string, string>();
  for (const f of jsFiles) virtual.set(VIRTUAL + f.path.replace(/\\/g, '/'), f.text);
  virtual.set(VIRTUAL + '__ambient.d.ts', AMBIENT);
  const options: ts.CompilerOptions = {
    allowJs: true, checkJs: true, noEmit: true, target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler, lib: ['lib.es2022.d.ts'], types: [], skipLibCheck: true,
    baseUrl: '/', paths, noImplicitAny: false, strict: false,
  };
  const host = ts.createCompilerHost(options);
  const realRead = host.readFile.bind(host);
  const realExists = host.fileExists.bind(host);
  const realSource = host.getSourceFile.bind(host);
  // Module resolution probes DIRECTORIES first: a virtual folder does not exist on disk, so say it does.
  const virtualDirs = new Set<string>();
  for (const k of virtual.keys()) for (let d = posix.dirname(k); d.length > 1 && !virtualDirs.has(d); d = posix.dirname(d)) virtualDirs.add(d);
  const realDir = host.directoryExists?.bind(host);
  host.directoryExists = d => virtualDirs.has(d.replace(/\/$/, '')) || (realDir ? realDir(d) : false);
  host.fileExists = f => virtual.has(f) || realExists(f);
  host.readFile = f => virtual.get(f) ?? realRead(f);
  host.getSourceFile = (f, lang, onError, shouldCreate) => {
    const text = virtual.get(f);
    return text !== undefined ? ts.createSourceFile(f, text, lang, true) : realSource(f, lang, onError, shouldCreate);
  };
  const roots = [...virtual.keys()];
  const program = ts.createProgram(roots, options, host);
  const checker = program.getTypeChecker();
  const display = (sf: ts.SourceFile): string => sf.fileName.slice(VIRTUAL.length);
  const covered = new Set<string>(); // file:line:col already reported by the checker

  // 1) The type checker: API existence problems and non-stable imports.
  let typeWarnings = 0;
  const warnings: Finding[] = [];
  /** True when the receiver of the property access at `start` has a type declared in the vendored typings (every union member). */
  const receiverIsVendored = (sf: ts.SourceFile, start: number): boolean => {
    let found: ts.PropertyAccessExpression | undefined;
    const seek = (n: ts.Node): void => {
      if (found || start < n.getFullStart() || start >= n.getEnd()) return;
      if (ts.isPropertyAccessExpression(n) && n.name.getStart(sf) === start) { found = n; return; }
      ts.forEachChild(n, seek);
    };
    seek(sf);
    if (!found) return false;
    const t = checker.getNonNullableType(checker.getTypeAtLocation(found.expression));
    const parts = t.isUnion() ? t.types : [t];
    return parts.length > 0 && parts.every(x => (x.symbol ?? x.aliasSymbol)?.declarations?.some(dd => /script-api-typings/.test(dd.getSourceFile().fileName)));
  };
  for (const f of jsFiles) {
    const sf = program.getSourceFile(VIRTUAL + f.path.replace(/\\/g, '/'));
    if (!sf) continue;
    for (const d of [...program.getSyntacticDiagnostics(sf), ...program.getSemanticDiagnostics(sf)]) {
      const start = d.start ?? 0;
      const loc = where(sf, start, f.path);
      const text = ts.flattenDiagnosticMessageText(d.messageText, ' ');
      if (d.code === MISSING_MODULE) {
        findings.push({ kind: 'module', ...loc, message: text });
        covered.add(`${loc.file}:${loc.line}:${loc.column}`);
      } else if (MISSING_MEMBER.has(d.code)) {
        const name = /'([^']+)'/.exec(text)?.[1] ?? '';
        const added = ADDED_AFTER.get(name);
        const betaOnly = BETA_ONLY.has(name);
        // A missing member on a type the SCRIPT declared (an inferred object literal) is not an API question.
        const apiReceiver = d.code !== 2339 && d.code !== 2551 ? true : receiverIsVendored(sf, start);
        if (!apiReceiver && !betaOnly && !added) { typeWarnings++; continue; }
        if (!apiReceiver) continue; // a compound name on an untyped/own receiver: the name pass below decides
        if (betaOnly || added) {
          findings.push({ kind: betaOnly ? 'beta-api' : 'newer-than-declared', ...loc, message: `${text}${betaOnly ? ' (beta-only API)' : ` (stable only from ${added})`}` });
          covered.add(`${loc.file}:${loc.line}:${loc.column}`);
        } else {
          // Neither stable nor beta names it: a typo, a removed API, or the typings being narrower than the script's own flow.
          warnings.push({ kind: 'unknown-api', ...loc, message: text });
          typeWarnings++;
        }
      } else typeWarnings++;
    }
  }

  // 2) Names on untyped receivers, plus the list of APIs used.
  const uses = new Map<string, ApiUse>();
  const record = (mod: string, name: string, st: ApiUse['stability'], first: string): void => {
    const key = `${mod}|${name}|${st}`;
    const cur = uses.get(key);
    if (cur) cur.count++;
    else uses.set(key, { module: mod, name, stability: st, count: 1, first });
  };
  const classify = (name: string, declaredIn: string): ApiUse['stability'] | undefined => {
    if (BETA_ONLY.has(name)) return 'beta';
    const added = ADDED_AFTER.get(name);
    if (!added) return undefined;
    const [mod, ver] = added.split('@') as [string, string];
    return olderThan(declared[mod] ?? declaredIn, ver) ? 'newer-than-declared' : undefined;
  };
  for (const f of jsFiles) {
    const sf = program.getSourceFile(VIRTUAL + f.path.replace(/\\/g, '/'));
    if (!sf) continue;
    const own = new Set<string>(); // names this file declares itself
    const collect = (n: ts.Node): void => {
      if ((ts.isPropertyAssignment(n) || ts.isMethodDeclaration(n) || ts.isPropertyDeclaration(n) || ts.isFunctionDeclaration(n) || ts.isVariableDeclaration(n) || ts.isParameter(n)) && n.name && ts.isIdentifier(n.name)) own.add(n.name.text);
      if (ts.isShorthandPropertyAssignment(n)) own.add(n.name.text);
      ts.forEachChild(n, collect);
    };
    collect(sf);
    const visit = (n: ts.Node): void => {
      let nameNode: ts.Identifier | ts.StringLiteral | undefined;
      if (ts.isPropertyAccessExpression(n) && ts.isIdentifier(n.name)) nameNode = n.name;
      else if (ts.isElementAccessExpression(n) && ts.isStringLiteral(n.argumentExpression)) nameNode = n.argumentExpression;
      else if (ts.isImportSpecifier(n)) nameNode = n.propertyName && ts.isIdentifier(n.propertyName) ? n.propertyName : n.name;
      if (nameNode) {
        const name = nameNode.text;
        const loc = where(sf, nameNode.getStart(sf), f.path);
        const first = `${loc.file}:${loc.line}`;
        const sym = ts.isImportSpecifier(n) ? checker.getSymbolAtLocation(n.name) : checker.getSymbolAtLocation(nameNode);
        const target = sym && sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
        const decl = target?.declarations?.[0];
        const declFile = decl?.getSourceFile().fileName ?? '';
        if (decl && /script-api-typings/.test(declFile)) {
          const owner = ownerOf(decl);
          record(moduleOfFile(declFile), owner ? `${owner}.${name}` : name, classify(name, '') ?? 'stable', first);
        } else if (!covered.has(`${loc.file}:${loc.line}:${loc.column}`) && isCompound(name) && !own.has(name)) {
          const st = classify(name, DEFAULT_DECLARED.server!);
          if (st) {
            const added = ADDED_AFTER.get(name);
            findings.push({
              kind: st === 'beta' ? 'beta-api' : 'newer-than-declared', ...loc,
              message: st === 'beta' ? `'${name}' exists only in the beta @minecraft typings (receiver is untyped)` : `'${name}' is stable only from ${added}, the manifest declares an older version (receiver is untyped)`,
            });
            record('(untyped)', name, st, first);
          }
        }
      }
      ts.forEachChild(n, visit);
    };
    visit(sf);
  }
  const apis = [...uses.values()].sort((a, b) => a.module.localeCompare(b.module) || a.name.localeCompare(b.name));
  findings.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line || a.column - b.column);
  return { ok: findings.length === 0, findings, warnings, apis, scriptsChecked: jsFiles.length, typeWarnings };
}

/** `[2, 9, 0]` or `"2.9.0"` -> `2.9.0`. */
function versionText(v: unknown): string {
  return Array.isArray(v) ? v.join('.') : String(v ?? '');
}

/** A manifest, as far as the audit reads it. */
interface ManifestLike { dependencies?: Array<{ module_name?: string; version?: unknown }> }

/**
 * Audit a whole pack given as `path -> text` (every `manifest.json` and `.js`). Scripts are grouped under the
 * nearest manifest and checked against the module versions THAT manifest declares.
 */
export function auditPackFiles(files: ReadonlyMap<string, string>): AuditResult {
  const manifests = [...files.keys()].filter(p => posix.basename(p) === 'manifest.json');
  const findings: Finding[] = [];
  const warnings: Finding[] = [];
  const apis = new Map<string, ApiUse>();
  let scriptsChecked = 0;
  let typeWarnings = 0;
  for (const mpath of manifests) {
    let manifest: ManifestLike;
    try { manifest = JSON.parse(files.get(mpath)!) as ManifestLike; } catch { findings.push({ kind: 'manifest', file: mpath, line: 1, column: 1, message: 'manifest.json is not valid JSON' }); continue; }
    const root = posix.dirname(mpath);
    const prefix = root === '.' ? '' : root + '/';
    const scripts = [...files.keys()].filter(p => p.startsWith(prefix) && /\.m?js$/.test(p) && /(^|\/)scripts\//.test(p));
    if (scripts.length === 0) continue;
    const declared: DeclaredVersions = {};
    const deps = (manifest.dependencies ?? []).filter(d => d.module_name);
    for (const d of deps) {
      const mod = d.module_name!;
      const v = versionText(d.version);
      if (!(STABLE_MODULES as readonly string[]).includes(mod)) findings.push({ kind: 'manifest', file: mpath, line: 1, column: 1, message: `dependency ${mod} ${v} is not a stable script module` });
      else if (!stableVersion(v)) findings.push({ kind: 'manifest', file: mpath, line: 1, column: 1, message: `dependency ${mod} version '${v}' is a pre-release (beta/rc/preview)` });
      else declared[mod.slice('@minecraft/'.length)] = v;
    }
    const sources = scripts.map(p => ({ path: p, text: files.get(p)! }));
    for (const s of sources) {
      for (const m of s.text.matchAll(/(?:from|import)\s*\(?\s*["'](@minecraft\/[\w-]+)["']/g)) {
        if (!deps.some(d => d.module_name === m[1])) {
          const line = s.text.slice(0, m.index).split('\n').length;
          findings.push({ kind: 'manifest', file: s.path, line, column: 1, message: `imports ${m[1]} but ${mpath} does not declare it as a dependency` });
        }
      }
    }
    const r = auditScripts(sources, { ...DEFAULT_DECLARED, ...declared });
    findings.push(...r.findings);
    warnings.push(...r.warnings);
    scriptsChecked += r.scriptsChecked;
    typeWarnings += r.typeWarnings;
    for (const a of r.apis) {
      const key = `${a.module}|${a.name}|${a.stability}`;
      const cur = apis.get(key);
      if (cur) cur.count += a.count; else apis.set(key, { ...a });
    }
  }
  return { ok: findings.length === 0, findings, warnings, apis: [...apis.values()].sort((a, b) => a.module.localeCompare(b.module) || a.name.localeCompare(b.name)), scriptsChecked, typeWarnings };
}

/** Read a pack (folder, `.mcaddon`, `.mcpack`, `.zip`; nested archives included) into `path -> text` for manifests and scripts. */
export function readPackFiles(path: string, prefix = ''): Map<string, string> {
  const into = new Map<string, string>();
  const addEntry = (name: string, data: Uint8Array): void => {
    if (/\.(mcpack|mcaddon|zip)$/i.test(name)) {
      for (const [n, d] of Object.entries(unzipSync(data))) addEntry(`${name}!/${n}`, d);
    } else if (/(^|\/)manifest\.json$|\.m?js$/.test(name)) into.set(name, new TextDecoder().decode(data));
  };
  if (statSync(path).isDirectory()) {
    const walk = (dir: string, rel: string): void => {
      for (const e of readdirSync(dir, { withFileTypes: true })) {
        const full = join(dir, e.name);
        if (e.isDirectory()) walk(full, `${rel}${e.name}/`);
        else addEntry(prefix + rel + e.name, new Uint8Array(readFileSync(full)));
      }
    };
    walk(path, '');
  } else if (['.mcaddon', '.mcpack', '.zip'].includes(extname(path).toLowerCase())) {
    for (const [n, d] of Object.entries(unzipSync(new Uint8Array(readFileSync(path))))) addEntry(n, d);
  } else throw new Error(`not a pack folder or archive: ${path}`);
  return into;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const jsonOut = args.find(a => a.startsWith('--json='))?.slice(7);
  const packs = args.filter(a => !a.startsWith('--'));
  if (packs.length === 0) { console.error('usage: bun scripts/_script_api_audit.ts <pack.mcaddon|folder>... [--json=<report.json>]'); process.exit(2); }
  let failed = false;
  const reports: Record<string, AuditResult> = {};
  for (const p of packs) {
    const r = auditPackFiles(readPackFiles(p));
    reports[p] = r;
    const beta = r.apis.filter(a => a.stability !== 'stable').length;
    console.log(`${p}: ${r.scriptsChecked} scripts, ${r.apis.length} APIs (${beta} not stable), ${r.findings.length} findings, ${r.warnings.length} unknown-member warnings, ${r.typeWarnings} other type warnings`);
    for (const f of r.findings) console.log(`  ${f.kind}  ${f.file}:${f.line}:${f.column}  ${f.message}`);
    for (const f of r.warnings) console.log(`  (warning) ${f.kind}  ${f.file}:${f.line}:${f.column}  ${f.message.slice(0, 160)}`);
    if (!r.ok) failed = true;
  }
  if (jsonOut) writeFileSync(jsonOut, JSON.stringify(reports, null, 1) + '\n');
  process.exit(failed ? 1 : 0);
}
